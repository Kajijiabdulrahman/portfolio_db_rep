-- ============================================================================
-- 4. Row Level Security (RLS)
--
-- RLS is ENABLED on every table with NO public policies. This is deliberate:
--   * Supabase auto-exposes every table through its REST/PostgREST API to the
--     anonymous ("anon") and "authenticated" roles. With RLS enabled and no
--     policies, those API roles are DENIED all access by default — the tables
--     cannot be read or written through the public API.
--   * The PHP application connects SERVER-SIDE with the postgres (SQL) role
--     over the direct/pooled PostgreSQL connection. That connection is not
--     subject to these RLS policies, so the website keeps full access.
--
-- Do NOT add "USING (true)" style allow-all policies just to make the public
-- API work — the PHP backend is the only intended database client.
-- (The service_role key must never be embedded in browser code; this project
--  does not use the Supabase JS/REST API at all.)
-- ============================================================================

ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE admins   ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects ENABLE ROW LEVEL SECURITY;

-- The Vite client uses the publishable anon key. Projects are public, while
-- contact submissions are insert-only for visitors. Admin message management
-- should be protected with Supabase Auth or a server-side edge function; the
-- frontend never receives a service-role key.
DROP POLICY IF EXISTS "Public can read projects" ON projects;
CREATE POLICY "Public can read projects"
  ON projects FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Public can submit messages" ON messages;
CREATE POLICY "Public can submit messages"
  ON messages FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    char_length(name) BETWEEN 2 AND 100
    AND char_length(email) BETWEEN 3 AND 150
    AND char_length(message) BETWEEN 10 AND 5000
    AND (subject IS NULL OR char_length(subject) <= 200)
  );
