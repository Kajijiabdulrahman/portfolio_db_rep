-- ────────────────────────────────────────────────────────────────────────────
-- 1. messages — contact form submissions
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS messages (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  email      VARCHAR(150) NOT NULL,
  subject    VARCHAR(200),
  message    TEXT         NOT NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  is_read    BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_messages_created_at ON messages (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_is_read    ON messages (is_read);

-- ────────────────────────────────────────────────────────────────────────────
-- 2. admins — admin panel accounts
--    Default login: admin / admin123
--    The hash below is a PHP bcrypt hash generated with:
--      password_hash('admin123', PASSWORD_DEFAULT)
--    Plain-text passwords are NEVER stored. Log in via /admin/login.php,
--    which uses password_verify(). To change the password, generate a new
--    hash with:  php -r "echo password_hash('new-password', PASSWORD_DEFAULT);"
--    and UPDATE the admins table with it.
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS admins (
  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

